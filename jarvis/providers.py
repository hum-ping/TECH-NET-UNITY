"""Replaceable async AI, speech, and notification provider interfaces."""
from __future__ import annotations
from typing import Any, AsyncIterator, Mapping, Protocol

class ProviderNotConfigured(RuntimeError): pass
class AIProvider(Protocol):
    async def chat(self, messages: list[Mapping[str, str]]) -> str: ...
    async def stream(self, messages: list[Mapping[str, str]]) -> AsyncIterator[str]: ...
    async def generate(self, prompt: str) -> str: ...
    async def embed(self, text: str) -> list[float]: ...
class TTSProvider(Protocol):
    async def speak(self, text: str) -> None: ...
class STTProvider(Protocol):
    async def transcribe(self, audio: Any) -> str: ...
class NotificationProvider(Protocol):
    async def notify(self, title: str, message: str, level: str = "info") -> None: ...
